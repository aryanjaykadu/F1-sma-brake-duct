"""Generate firmware/sma_rig/lap_profile.h from the transient lap model's spring environment.

The rig must give the spring wire the same heat balance as the car, not just the same numbers:
  blower %  inverts the rig blower curve so the air speed at the spring equals the car's U(t):
            rpm = 600 + 2400 d (d = duty, 0..1), air at the spring = 13 m/s x rpm / 3000
  lamp %    G_rig = G_car + 4 h(U) (T_air,car - T_room) / eps, i.e. the car's radiation plus the convective
            heat the warmer car air would have supplied (the rig air is room temperature);
            lamp duty = G_rig / 143.5 kW/m2 (lamp axis 23 mm from the spring line)
RIG CALIBRATION CONSTANTS (measure on the real rig before a run): blower curve and 13 m/s (anemometer at the
spring), lamp irradiance at 100 % (heat-flux gauge), room temperature.
One entry per 0.5 s of the car's last simulated lap (98.5 s).
"""
import json
import math
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
TAG = os.environ.get("LAP_TAG", "NiTiCu_Af76_gap3_eps0.8_d0.5")
G_100, U_100, RPM0, RPM_SPAN, RPM_MAX = 143.5e3, 13.0, 600.0, 2400.0, 3000.0
T_ROOM, EPS, D_W = 296.15, 0.8, 0.5e-3
T_WIRE_NOM = 335.0                     # mid-lap wire temperature for the film properties


def h_cyl(tf, u):
    """Churchill-Bernstein, as in phase2_transient_lap.py."""
    k = 0.0241 * (tf / 273.15) ** 0.81
    mu = 1.716e-5 * (tf / 273.15) ** 1.5 * (273.15 + 110.4) / (tf + 110.4)
    nu = mu / (101325 / (287.05 * tf))
    pr = 0.71
    re = max(u, 0.05) * D_W / nu
    return (0.3 + 0.62 * re ** 0.5 * pr ** (1 / 3) / (1 + (0.4 / pr) ** (2 / 3)) ** 0.25 *
            (1 + (re / 282000) ** 0.625) ** 0.8) * k / D_W


env = json.load(open(os.path.join(ROOT, "cfd", "transient", f"spring_env_{TAG}.json")))
t_air = env["T_air_K"]
rows, sat = [], 0
for g, u in zip(env["G_W_m2"], env["U_m_s"]):
    d_fan = ((u / U_100) * RPM_MAX - RPM0) / RPM_SPAN
    g_rig = g + 4 * h_cyl(0.5 * (T_WIRE_NOM + t_air), u) * (t_air - T_ROOM) / EPS
    h_pct = 100 * g_rig / G_100
    sat += h_pct > 100
    rows.append((max(0, min(100, round(h_pct))), max(10, min(100, round(100 * d_fan)))))
step_ms = int(round(env["dt_s"] * 1000))
lines = [f"// Generated by firmware/gen_lap_profile.py from cfd/transient/spring_env_{TAG}.json - do not edit.",
         f"// {len(rows)} steps of {step_ms} ms = {len(rows) * step_ms / 1000:.1f} s lap, {{lamp %, blower %}}.",
         f"// Lamp: car radiation + convective make-up for {t_air - 273.15:.1f} C car air vs {T_ROOM - 273.15:.0f} C room,",
         f"// / {G_100 / 1e3:.1f} kW/m2. Blower: inverse of rpm = {RPM0:.0f} + {RPM_SPAN:.0f} d, {U_100:.0f} m/s at {RPM_MAX:.0f} rpm.",
         f"// Lamp saturated (100 %) in {sat} of {len(rows)} steps.",
         "#pragma once",
         f"#define LAP_STEP_MS {step_ms}",
         f"#define LAP_STEPS {len(rows)}",
         "static const uint8_t LAP_PROFILE[LAP_STEPS][2] RIG_FLASH = {"]
for k in range(0, len(rows), 10):
    lines.append("    " + " ".join(f"{{{h},{f}}}," for h, f in rows[k:k + 10]))
lines.append("};")
out = os.path.join(ROOT, "firmware", "sma_rig", "lap_profile.h")
open(out, "w", newline="\n").write("\n".join(lines) + "\n")
print("WROTE", out, len(rows), "steps; lamp", min(r[0] for r in rows), "-", max(r[0] for r in rows),
      "%, blower", min(r[1] for r in rows), "-", max(r[1] for r in rows), "%, lamp saturated", sat)
